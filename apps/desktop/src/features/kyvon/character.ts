/**
 * A saved character configuration.
 *
 * Appearance only. No field here may reference a server, a credential or any
 * infrastructure identifier: a preset is meant to be exportable and shareable,
 * so anything secret placed in it would leak the moment someone shared their
 * KYVON. `isSafePreset` enforces that rather than leaving it to review.
 */
export interface CharacterPreset {
  version: 1;
  characterId: Variant;
  petId: string;
  expression: CharacterState;
  accentColor: string;
}

export const DEFAULT_PRESET: CharacterPreset = {
  version: 1,
  characterId: 'kyvon-m',
  petId: 'k10',
  expression: 'idle',
  accentColor: '#38bdf8',
};

/** Keys that must never appear in a preset, at any depth. */
const FORBIDDEN = [
  'key',
  'token',
  'secret',
  'password',
  'passphrase',
  'credential',
  'ssh',
  'host',
  'server',
  'api',
  'auth',
  'cookie',
];

/**
 * Reject a preset carrying anything that looks like a credential or an
 * infrastructure identifier.
 *
 * Applied on load as well as on save, because a preset can arrive from a file
 * or a shared link — untrusted input, not just our own output.
 */
export function isSafePreset(value: unknown): value is CharacterPreset {
  if (typeof value !== 'object' || value === null) return false;
  const preset = value as Record<string, unknown>;

  if (preset.version !== 1) return false;
  if (!CHARACTERS.some((c) => c.id === preset.characterId)) return false;
  if (!PETS.some((p) => p.id === preset.petId)) return false;
  if (typeof preset.expression !== 'string' || !(preset.expression in STATES)) return false;
  if (typeof preset.accentColor !== 'string' || !/^#[0-9a-f]{6}$/i.test(preset.accentColor)) {
    return false;
  }

  // An unexpected key is refused rather than ignored: silently dropping it
  // would let a crafted preset round-trip through a share link.
  const allowed = new Set(Object.keys(DEFAULT_PRESET));
  for (const key of Object.keys(preset)) {
    if (!allowed.has(key)) return false;
    if (FORBIDDEN.some((f) => key.toLowerCase().includes(f))) return false;
  }
  return true;
}
