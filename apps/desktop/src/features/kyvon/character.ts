/**
 * The KYVON character model: states, pets, and the preset a visitor saves.
 *
 * This file is deliberately free of any 3D or AI dependency. The states are
 * what the viewer animates and what the AI pipeline drives, so keeping them as
 * plain data means both sides can be tested without a WebGL context or a
 * provider key — and the preset can be validated before anything renders.
 */

/**
 * What KYVON is doing, which drives animation, expression and status text.
 *
 * `offline` and `error` exist as first-class states rather than being folded
 * into `idle`: a companion that looks calm while its backend is unreachable is
 * telling the user something false, and this project's recurring defect has
 * been exactly that.
 */
export type CharacterState =
  | 'idle'
  | 'listening'
  | 'thinking'
  | 'speaking'
  | 'happy'
  | 'concerned'
  | 'warning'
  | 'success'
  | 'offline'
  | 'error';

export interface StatePresentation {
  /** Animation clip name as exported from Blender. */
  clip: string;
  label: string;
  /** Token name, not a raw colour — status must not depend on colour alone. */
  tone: 'neutral' | 'active' | 'positive' | 'caution' | 'danger' | 'muted';
  /** Read by assistive technology; every state is announced, not just shown. */
  announce: string;
}

